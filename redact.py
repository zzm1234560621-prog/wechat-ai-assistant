"""送云端前脱敏：把要发给第三方大模型 API 的文本里的敏感信息打码。

**背景**：现在 README 里那条路上，整段聊天记录是**原文**直接 POST 给
DeepSeek / Claude / 通义 的，而聊天记录里出现手机号、身份证、银行卡、
邮箱、IP 是常态。这些一旦出去就收不回来了。

**这个模块只处理"送出去的那一份文本"**：

  * **绝不许改本地原文**。聊天记录、`settings.json`、任何落盘的东西都不动，
    `redact()` 是纯函数（输入字符串、输出新字符串），不写文件、不改全局。
  * **默认关闭**。`config.yaml` 的 `privacy.redact` 严格按 `is True` 判定，
    和项目里 `shell.enabled` 一个风格：配置写错（缺字段、写成 `"true"` 字符串、
    `privacy` 是标量）一律当**关闭**——fail-safe 的方向是"保守"，
    但"保守"在这里指"不改变现有行为"，不是"偷偷开始改用户的文本"。
    开不开是用户的事，程序不替他决定。
  * **不许过度脱敏**。见 `patterns()` 上面的注释：普通年份、金额、QQ 号、
    6 位以内数字、时间戳、消息序号、**版本号**都**不能**被打码——把「2026 年」
    码成「20**」等于把可读性毁掉，模型也就答不对了。宁可漏几个，
    不可把整段文本打成马赛克（这条比"多码一点"重要）。
  * **正则不许有灾难性回溯**。所有 pattern 都是"定长/有限量词 + 明确分隔"，
    没有嵌套量词（`(\\d+)+` 那种）。理由很实在：输入是**别人发来的聊天记录**，
    不可控；一条能回溯爆炸的正则会让 bot 卡死在发消息前。

打码格式都保留可读性，让人一眼看出"这里被码了"而不是"这里丢了"：
手机号 `138****1234`、身份证 `110101********1234`、银行卡 `***************0123`
（等长 `*` 占位，看得出原来是几位）、邮箱 `zh***@example.com`、IP `192.168.*.*`。
"""
import re

# ------------------------------------------------------------
#  配置开关
# ------------------------------------------------------------

def enabled(cfg):
    """脱敏开了没有。**严格按 `is True` 判定**（`privacy.redact` 必须就是 True）。

    故意不做真值转换：`redact: "true"`（字符串）、`redact: 1`（数字）、
    `privacy: yes`（标量）**全部当关闭**。理由和 `executor.enabled` 一样——
    配置是人手写的 YAML，`"false"` 在 Python 里是真值，用 `bool()` 判会把
    "我明明写了 false" 变成"开了"，方向完全反了。
    """
    if not isinstance(cfg, dict):
        return False
    priv = cfg.get("privacy")
    if not isinstance(priv, dict):
        return False
    return priv.get("redact", False) is True


# ------------------------------------------------------------
#  匹配规则
# ------------------------------------------------------------
# 设计原则（也是反例清单，写测试时照着钉）：
#
#   1. **手机号**：中国手机号是 `1[3-9]` 开头 + 9 位 = 11 位，且必须**不挨着
#      别的数字**。所以前后加 `(?<!\d)` / `(?!\d)`：这样「订单号 20261001123」
#      这种 11 位数字串里嵌的 `101001123` 不会因为"119 开头？"被误伤
#      （它压根不以 1[3-9] 开头，但加上边界能挡住更多形态）。
#   2. **身份证**：18 位，`\d{17}[\dXx]`，同样加数字边界。前 6 位地区码 + 
#      8 位生日 + 3 位顺序 + 1 位校验。**只匹配 18 位**，15 位老号码不匹配
#      （那个和普通长数字太容易混，宁可不码）。
#   3. **银行卡**：`\d{16,19}` 且**前后是边界**（不是数字、不是点）。这一条
#      最容易误伤，所以：① 强制 16 位起步（普通金额/订单号不会这么长）；
#      ② 脱敏时**长数字串里只保留后 4 位**，一眼能对上。
#   4. **邮箱**：必须有 `@` 和带点的域名，本地部分 2 个字符以上才码
#      （`a@b.com` 那种太短，码了也看不出原样，不如不码）。TLD 要求
#      **至少 2 个字符**（`\.[A-Za-z]{2,}`），避免把 `x@y.z` 这种当邮箱。
#   5. **IPv4**：四段 0-255。这里**只做范围校验**，不做"公网/内网"区分——
#      内网 IP（192.168.x.x）也是环境信息，一起码掉更省心。
#      额外一道闸（`_has_version_marker`）：`1.2.3.4` 这种**版本号**在语法上和
#      IPv4 完全一样，纯靠数字分不开——只能看它前后的词。前面紧挨着
#      「版本/版本号/ver/version/v/Python/内核」就当版本号**不码**
#      （用户装了什么版本不是隐私，码掉反而看不出在说哪个版本）。
#      这是本项目最典型的"过度脱敏"反例，测试里钉着。
#      代价：`版本：1.2.3.4` 这种中间隔了标点的会漏——**宁可漏，
#      不可把版本号打成 `1.2.*.*`**。
#
# **明确不打码**（测试里有反例）：
#   * `2026`、`2026-10-01`（年份/日期：4 位数字，够不到任何上面的门槛）
#   * `12345`、`123456`（6 位以内数字）
#   * `¥3200`、`3200.50`（金额：位数不够 + 带小数点，被边界挡住）
#   * `12345678901`（11 位但开头是 1 后面跟 2 —— 不是手机号段，不码）
#   * QQ 号（5~11 位普通数字，和金额同理）
#   * 时间戳 `1759286400`（10 位数字，够不到 16 位）
#   * 消息序号 / rowid（小整数）
#   * `版本号 1.2.3.4`、`v1.2.3.4`（版本号，见上）
_RE_PHONE = re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")
_RE_IDCARD = re.compile(r"(?<!\d)\d{17}[\dXx](?!\d)")
# 16~19 位连续数字；前后不许是数字，也不许是小数点（挡 3200.1234567890123 这种）
_RE_BANKCARD = re.compile(r"(?<![\d.])\d{16,19}(?![\d.])")
_RE_EMAIL = re.compile(r"[A-Za-z0-9._%+-]{2,}@[A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}")
_OCTET = r"(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)"
_RE_IPV4 = re.compile(r"(?<![\d.])" + r"\.".join([_OCTET] * 4) + r"(?![\d.])")

# 「这个四段数字不是 IP，是版本号」的判据（**用代码判，不塞进正则**）。
# 踩过的坑：硬写 lookbehind 只能拆成一堆等长分支，而且依赖插入位置——
# `(?<!版本)` 在「版本号 1.2.3.4」前面根本不成立（紧邻的字符是「号」），
# 拆漏一个分支就是静默漏判。所以改成直接看前后各几个字符。
#
# 引导词分两档，因为 `v` 太短、太容易在别处出现：
#   * 长引导词可以带空格：`版本 1.85.4`、`version 2.0.0.1`
#   * `v` 必须**紧贴**数字（`v1.2.3.4`）——否则「IP 是 v 后面 1.2.3.4」
#     这种正常句子会被整句放过（用 `(?![A-Za-z])` 挡住 `revert1.2.3.4`）。
_VERSION_WORDS = re.compile(
    r"(?:版本号?|version|ver|Python|python|内核|固件|node|Node)\s*$")
_VERSION_V_NOSPACE = re.compile(r"(?<![A-Za-z])v$")
# `v` 后面带空格也算版本号（`v 1.2.3.4`）——但这只在"前面没有别的东西"时成立，
# 见 _has_version_marker 里的额外条件。
_VERSION_V_SPACE = re.compile(r"(?<![A-Za-z])v\s$")
# 它自己只是长版本号的**前半截**：`Python 3.11.9` 里的 `3.11` 后面还接着 `.9`。
# 判据 = 紧挨着后面的那个字符是 `.`；不往后扫，所以
# 「Python 3.11.9 连 1.2.3.4」里后面那个真 IP 照样被码。
_VERSION_AFTER = re.compile(r"\.")
# 回看窗口：要够放下「手机上的版本 」这种前缀。留窄了这条规则就白写。
_VERSION_LOOKBACK = 16


def patterns():
    """返回 `[(名称, 编译好的正则), ...]`。顺序 = 应用顺序（**不要随意调换**）。

    为什么顺序重要：身份证（18 位）会在银行卡（16~19 位）之前匹配掉，
    这样 18 位身份证就不会被银行卡规则按"只留后 4 位"处理。
    两个都加了数字边界，所以**已经打过码的文本不会再被后面的规则命中**
    （`*` 不是数字，边界自然成立）——这点是"幂等"的保证。
    """
    return [
        ("身份证", _RE_IDCARD),
        ("银行卡", _RE_BANKCARD),
        ("手机号", _RE_PHONE),
        ("邮箱", _RE_EMAIL),
        ("IPv4", _RE_IPV4),
    ]


# ------------------------------------------------------------
#  打码函数
# ------------------------------------------------------------

def _mask_phone(m, src):
    s = m.group(0)
    return s[:3] + "****" + s[-4:]


def _mask_idcard(m, src):
    s = m.group(0)
    # 前 6 位（地区码）+ 8 个星 + 后 4 位，总长仍是 18、位置对得上
    return s[:6] + "********" + s[-4:]


def _mask_bankcard(m, src):
    s = m.group(0)
    # 只留后 4 位；前面用等长的 * 占位，让人看得出"这里原来是几位数字"
    return "*" * (len(s) - 4) + s[-4:]


def _mask_email(m, src):
    s = m.group(0)
    local, _, domain = s.partition("@")
    if len(local) <= 2:
        head = local[:1]
    else:
        head = local[:2]
    return head + "***@" + domain


def _version_marker_in(prefix):
    """这段"紧挨着 IP 前面"的文本，结尾是不是版本号引导词。"""
    if _VERSION_WORDS.search(prefix) or _VERSION_V_NOSPACE.search(prefix):
        return True
    # `v 1.2.3.4`：v 后面带空格也算。但为避免「…v 是变量，地址 1.2.3.4」这种
    # 正常句子被误放过，要求这段前缀里**除了 v 没别的实义字符**。
    m = _VERSION_V_SPACE.search(prefix)
    return bool(m) and prefix[:m.start()].strip() == ""


def _has_version_marker(text, start, end):
    """「这个 IPv4 形状的串其实是版本号」→ True（**不打码**）。

    处理 `版本号 1.2.3.4`、`v1.2.3.4`、`Python 3.11.9 和 1.2.3.4` 这类：它们和
    IPv4 都是 `\\d+.\\d+.\\d+.\\d+` 的形状，光看数字分不出谁是谁。判据只看
    **紧挨着的上下文**（这是刻意的：不往后扫，才不会把
    `Python 3.11.9 连 1.2.3.4` 里的真 IP 一起放过）：

      * 前面紧挨着版本号引导词（可带空格）→ `版本 1.85.4`、`内核 5.15.0.1`；
      * 前面紧贴着 `v` → `v1.2.3.4`；
      * 后面紧挨着 `.` → 它只是长版本号的前半截（`Python 3.11.9` 里的 `3.11`）；
      * 其余（前面是空格/冒号/斜杠/中文标点）→ **真 IP**，照码。

    宁可漏几个 IP，也不要把版本号打成 `1.2.*.*`——那是过度脱敏，
    会把用户真正想问的东西（"哪个版本"）改坏。
    """
    prefix = text[max(0, start - _VERSION_LOOKBACK):start]
    if _version_marker_in(prefix):
        return True
    return bool(_VERSION_AFTER.match(text, end))


def _mask_ipv4(m, src):
    """IP 打码。先判是不是版本号（同一个形状），是就原样放回。

    返回原文表示"这不是敏感信息"，调用方据此**不计命中次数**。
    """
    if _has_version_marker(src, m.start(), m.end()):
        return m.group(0)
    parts = m.group(0).split(".")
    return f"{parts[0]}.{parts[1]}.*.*"


# 每个打码函数都是 `f(匹配对象, 当前文本) -> 替换文本`。第二个参数给的是
# **当前文本**（前几条规则替换之后的那份），IP 那条要用它看上下文。
_MASKERS = {
    "手机号": _mask_phone,
    "身份证": _mask_idcard,
    "银行卡": _mask_bankcard,
    "邮箱": _mask_email,
    "IPv4": _mask_ipv4,
}


def redact(text, cfg=None):
    """把 `text` 里的敏感信息打码，返回 `(新文本, 命中次数)`。

    * `enabled(cfg)` 为假 → **原样返回** `(text, 0)`（一个字符都不动）。
    * `text` 不是字符串（None / 数字）→ 原样返回，命中 0，不抛。
    * **不修改任何本地文件**，也不改传入的对象（字符串本来就不可变）。

    只处理**送出去的那一份文本**：调用方拿到返回值以后再去 POST，本地原文
    （聊天记录、日志、settings.json）一个字都不改。
    """
    if not enabled(cfg):
        return text, 0
    if not isinstance(text, str) or not text:
        return text, 0

    hits = 0
    out = text
    for name, rx in patterns():
        # `out` 每轮都在变，值要**显式绑**给闭包参数，别让它闭包到循环变量
        # （IP 那条要拿"当前文本"看前面是不是「版本号」）。
        _src = out
        _masker = _MASKERS[name]

        def _sub(m, _src=_src, _masker=_masker):
            nonlocal hits
            masked = _masker(m, _src)
            if masked != m.group(0):
                hits += 1          # 只有**真的改动过**才算命中一次
            return masked

        out = rx.sub(_sub, out)
    return out, hits


# ------------------------------------------------------------
#  独立自测入口（纯逻辑，不联网、不碰任何项目文件）
# ------------------------------------------------------------

if __name__ == "__main__":
    _ON = {"privacy": {"redact": True}}
    _txt = "手机13812341234 身份证110101199001011234 卡6222021234567890123 邮箱zhangsan@example.com IP 192.168.1.7"
    _r, _n = redact(_txt, _ON)
    print("命中", _n, "处：")
    print(_r)
    for _case in ["2026 年花了 ¥3200", "12345", "QQ 123456789", "时间戳 1759286400",
                  "版本号 1.2.3.4", "v1.2.3.4", "version 2.0.0.1", "Python 3.11.9"]:
        _rr, _nn = redact(_case, _ON)
        assert _nn == 0, f"不该打码却命中了：{_case} → {_rr}"
    _ip, _ipn = redact("服务器 192.168.1.7", _ON)
    assert _ipn == 1 and "192.168.*.*" in _ip, f"真 IP 还是要码：{_ip}"
    _mix, _mixn = redact("Python 3.11.9 连 1.2.3.4 不通", _ON)
    assert _mixn == 1 and "Python 3.11.9 连 1.2.*.*" in _mix, f"同句混合判错：{_mix}"
    assert redact(_txt, {}) == (_txt, 0), "默认关闭时必须原样返回"
    print("redact.py 自测通过 ✅")
